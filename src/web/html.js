'use strict';

/** Auto-escaping HTML templates. Interpolated values are escaped unless wrapped with raw(). */
class Safe { constructor(s) { this.s = String(s); } toString() { return this.s; } }
const raw = (s) => new Safe(s);
const esc = (v) => String(v).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

function render(v) {
  if (v === null || v === undefined || v === false) return '';
  if (v instanceof Safe) return v.s;
  if (Array.isArray(v)) return v.map(render).join('');
  return esc(v);
}

function html(strings, ...values) {
  let out = strings[0];
  for (let i = 0; i < values.length; i++) out += render(values[i]) + strings[i + 1];
  return new Safe(out);
}

module.exports = { html, raw, esc, Safe };
